export const meta = {
  name: 'solid-groove-ship',
  description: 'Ship one Groove issue: triage it as a feature, fix or polish, build it, review features, and open PRs that merge themselves once green',
  whenToUse:
    'Run to ship ONE Linear issue (team GRV) whose spec has been agreed in the issue body. Pass the identifier: { issue: "GRV-123" } (or just "GRV-123"). Triage picks the kind of work and stops only if the issue is genuinely unclear; the build runs unattended; features get an adversarial review with up to two fix rounds; every PR opens ready for review against main, with screenshots for any UI change, one at a time (each after the one before it has merged), and merges on its own once CI passes unless it touches a gated path; the issue is QA\'d on production after the PR that completes it lands.',
  phases: [
    { title: 'Triage', detail: 'read the issue, pick feature / fix / polish and the model tier', model: 'sonnet' },
    { title: 'Build', detail: 'implement, test, push branches, capture screenshots' },
    { title: 'Review', detail: 'features only: adversarial review, up to two fix rounds' },
    { title: 'Land', detail: 'open each PR against main once the one before it has merged; merge.yml queues the safe ones', model: 'sonnet' },
  ],
}

// One pipeline for every kind of work. The process scales with the kind rather
// than living in three separate pipelines: a fix proves itself with a red-first
// regression test, polish with a unit test where one makes sense, and only a
// feature pays for an adversarial review. Questions belong to the interactive
// shape session before this runs, so nothing here waits on a person except a
// genuinely unclear issue.

const issue = String((args && typeof args === 'object' ? args.issue : args) ?? '').trim().toUpperCase()
if (!/^[A-Z][A-Z0-9]*-\d+$/.test(issue)) throw new Error('Pass the Linear identifier: { issue: "GRV-123" } or "GRV-123"')

const MAX_FIX_ROUNDS = 2
const IMPLEMENTER = '.claude/agents/solid-groove-implementer.md'
const REVIEWER = '.claude/agents/solid-groove-reviewer.md'
const brief = (path) => `Read \`${path}\` and follow it as your operating instructions.\n\n`

// Model routing. Triage picks the cheapest tier the issue's complexity and
// novelty allow; the build, its fixes and the review run on it. A feature never
// builds on Haiku, a review never runs below Sonnet, and a build that comes back
// empty or unreproduced is retried once a tier up before the run gives up.
const TIERS = ['haiku', 'sonnet', 'opus']
const atLeast = (tier, floor) => TIERS[Math.max(TIERS.indexOf(tier), TIERS.indexOf(floor))]
const nextTier = (tier) => TIERS[Math.min(TIERS.indexOf(tier) + 1, TIERS.length - 1)]

const GITHUB = `Linear and GitHub: the issue is a Linear card in team GRV; read it with \`node .github/scripts/linear.mjs issue ${issue}\` (comments included), comment with \`node .github/scripts/linear.mjs comment ${issue} --body-file <file>\`, and move it with \`node .github/scripts/linear.mjs state ${issue} "<column>"\` (LINEAR_API_KEY is set). The code is in \`trygroove/groove\` on GitHub: use the \`gh\` CLI if \`gh auth status\` succeeds (in a Claude Code cloud session \`gh api\` works even when \`gh auth status\` says the token is invalid; \`gh pr\`/\`gh issue\` do not), otherwise the GitHub MCP tools (load them with ToolSearch, e.g. "select:mcp__github__create_pull_request"). End every comment and PR body you write with a blank line, a \`---\` rule, then \`_Generated by [Claude Code](https://claude.ai/code)_\`.`

const ENV = `## Your worktree and environment

- You are in a git worktree. \`cd "$(git rev-parse --show-toplevel)"\` first and use relative paths; an absolute \`/home/user/groove/...\` path is a different checkout.
- Branch from a remote ref (\`origin/main\` or \`origin/<branch>\`), never from wherever the worktree starts. Never pipe a git command through \`head\`/\`tail\` in an \`&&\` chain; it hides a failed checkout.
- Run \`bun install\` first. Without it \`bun run typecheck\` fails with TS2688 on '@testing-library/jest-dom'; that is a missing install, not a tsconfig problem.
- Audio suites need a default ALSA device. If they fail with "cpal backend error ... DeviceUnavailable", run \`printf 'pcm.!default {\\n    type null\\n}\\nctl.!default {\\n    type null\\n}\\n' > ~/.asoundrc\` and retry. Never mock Tone or skip an audio suite.
- Only Chromium runs here (\`bun run test:browser:emulator:chromium\`). Per push, CI runs only a Chromium @sanity subset of the emulator browser suite; the full matrix runs daily on main. So run the Chromium pre-flight for any change a browser can see.
`

const TRIAGE_SCHEMA = {
  type: 'object',
  required: ['kind', 'tier', 'tierReason', 'title', 'slug', 'unclear', 'question', 'changesUi', 'existingPr', 'waitFor'],
  properties: {
    kind: { type: 'string', enum: ['feature', 'fix', 'polish'] },
    tier: { type: 'string', enum: TIERS, description: 'The model the build runs on' },
    tierReason: { type: 'string', description: 'Why that tier, in one sentence' },
    title: { type: 'string', description: 'What the work does, in a few words, for PR titles' },
    slug: { type: 'string', description: 'Short kebab-case slug for branch names, no issue number' },
    unclear: { type: 'boolean', description: 'True only if two reasonable readings would build materially different things and nothing decides between them' },
    question: { type: 'string', description: 'The one question that unblocks it, if unclear; else empty' },
    changesUi: { type: 'boolean' },
    existingPr: { type: 'string', description: 'URL of an open PR that already closes or completes this card, else empty' },
    waitFor: { type: 'array', items: { type: 'string' }, description: 'Open PRs (as "#n") whose changes this work would likely conflict with, else empty' },
  },
}

const BUILD_SCHEMA = {
  type: 'object',
  required: ['outcome', 'branches', 'summary', 'assumptions', 'checks', 'uiChanged', 'screenshots'],
  properties: {
    outcome: { type: 'string', enum: ['built', 'unclear', 'unreproduced'] },
    question: { type: 'string', description: 'If unclear or unreproduced: the question, or what was tried' },
    branches: {
      type: 'array',
      description: 'Pushed branches in landing order; the first is based on main, each later one on the branch before it',
      items: {
        type: 'object',
        required: ['branch', 'purpose'],
        properties: { branch: { type: 'string' }, purpose: { type: 'string' } },
      },
    },
    summary: { type: 'string', description: 'What was built or fixed' },
    rootCause: { type: 'string', description: 'Fix only: the cause in one sentence' },
    redEvidence: { type: 'string', description: 'Fix only: verbatim failure output of the regression test before the fix' },
    assumptions: { type: 'array', items: { type: 'string' } },
    checks: { type: 'string', description: 'Commands run and their real results' },
    uiChanged: { type: 'boolean' },
    screenshots: { type: 'string', description: 'Markdown from walkthrough:publish, or empty when no UI changed' },
    rulesChanged: { type: 'boolean', description: 'True if firestore.rules or storage.rules changed' },
    cloudApis: { type: 'array', items: { type: 'string' }, description: 'Each Google Cloud API the branches need that production does not use yet, as "<api>: why it is required (the code that needs it and what that code does), on <branch>", e.g. "cloudscheduler.googleapis.com: purgeExpiredTranscripts is an onSchedule function that deletes expired transcripts hourly, and Firebase deploys it as a Cloud Scheduler job, on claude/grv-8-retention"; else empty' },
  },
}

const REVIEW_SCHEMA = {
  type: 'object',
  required: ['blocking', 'nonBlocking'],
  properties: {
    blocking: { type: 'array', items: { type: 'string' } },
    nonBlocking: { type: 'array', items: { type: 'string' } },
  },
}

const WAIT_SCHEMA = {
  type: 'object',
  required: ['state'],
  properties: {
    state: { type: 'string', enum: ['merged', 'closed', 'waiting'], description: 'merged; closed without merging; or still open when the wait ran out' },
    labels: { type: 'array', items: { type: 'string' }, description: 'The PR\'s labels when the wait ended' },
  },
}

const LAND_SCHEMA = {
  type: 'object',
  required: ['number', 'url'],
  properties: {
    number: { type: 'number' },
    url: { type: 'string' },
    problems: { type: 'array', items: { type: 'string' } },
  },
}

// ---------------------------------------------------------------- Triage
phase('Triage')
const t = await agent(
  `Triage Linear issue ${issue} for an unattended build. ${GITHUB}

Read the issue body and every comment. Decide:
- **kind**: \`feature\` (new capability: one PR, or a few in sequence when a part can land first), \`fix\` (something is wrong), or \`polish\` (a small enhancement or tweak). The issue's own label does not decide it. Behaviour that works as coded but is not what the issue wants is a fix or polish, never a reason to stop.
- **unclear**: true only if two reasonable readings would build materially different things and nothing in the issue, its comments, a core flow or the code decides. Terse is not unclear; a missing cause is not unclear (finding it is the job). If unclear, post the single question as a comment on the card, written so a one-line answer unblocks it, and move the card to Blocked.
- **tier**: the cheapest model that will build it well, from the issue's complexity and novelty. A \`model:haiku\`, \`model:sonnet\` or \`model:opus\` label on the card decides it outright. Otherwise:
  - \`haiku\`: a fix or polish the spec pins down exactly (copy, styling, a constant, a missing guard, a wrong condition) in one or two files, following a pattern the code already has, touching no contract (domain, commands, persistence, rules, functions, audio graph, analytics catalog).
  - \`sonnet\`: the default. Work that extends existing patterns across a few files: a fix whose cause is findable, polish that needs a test, a feature that adds to an existing surface the way its neighbours do.
  - \`opus\`: novel or risky work: a new module or a pattern the codebase does not have yet, a contract change, real-time audio, streaming or concurrency, security rules or server code, a cause not yet known in a hard area, or a feature that ships as several PRs.
  When two tiers both fit, take the higher one. Say why in **tierReason**.
- **existingPr**: an open PR that already closes or completes ${issue} (its body says \`Closes ${issue}\` or \`Completes ${issue}\`), if any.
- **waitFor**: the open PRs this work would likely conflict with. List them (\`gh pr list --repo trygroove/groove --state open --json number,title,body\`) and look at each one's changed files (\`gh api repos/trygroove/groove/pulls/<n>/files --jq '.[].filename'\`) against the files and modules this issue will touch. A likely conflict is the same file, or the same module where both change behaviour; a PR in another area is not one. If there are any, hold off, so that it restarts by itself once they merge: for each PR, find the card its body names (\`Closes\`, \`Completes\` or \`Refs GRV-<n>\`) and record it as a blocker (\`node .github/scripts/linear.mjs blocks GRV-<n> ${issue}\`); comment on the card naming the PRs and the files they share, and saying it starts again on its own once they merge; and move the card back to Ready (the board's poll leaves a Ready card alone until each blocker reaches QA). Only if a PR names no card, or its card is already in QA or Done while the PR is still open, can a blocker not hold it: then say the product owner should move the card to Ready again once that PR has landed, and move the card to Backlog instead. Two changes landing at once in one area is how merge conflicts start.

Read only enough code to answer. Do not change anything else.`,
  { label: `triage ${issue}`, schema: TRIAGE_SCHEMA, model: 'sonnet', effort: 'medium' },
)
if (!t) throw new Error('Triage returned nothing')
let tier = atLeast(TIERS.includes(t.tier) ? t.tier : 'opus', t.kind === 'feature' ? 'sonnet' : 'haiku')
if (t.existingPr) {
  log(`${issue} already has an open PR: ${t.existingPr}. Nothing to do.`)
  return { issue, stopped: 'existing-pr', pr: t.existingPr }
}
if (t.unclear) {
  log(`${issue} is unclear; asked on the card: ${t.question}`)
  return { issue, stopped: 'unclear', question: t.question }
}
if (t.waitFor?.length) {
  log(`${issue} would likely conflict with ${t.waitFor.join(', ')}; holding off until they land.`)
  return { issue, stopped: 'wait-for', waitFor: t.waitFor }
}
log(`${issue} is ${t.kind} on ${tier}: ${t.title} (${t.tierReason})`)

// ---------------------------------------------------------------- Build
phase('Build')
const buildOn = (model) => agent(
  `${brief(IMPLEMENTER)}Build Linear issue ${issue} ("${t.title}"). Kind: **${t.kind}**. Branch slug: \`${t.slug}\`. ${GITHUB}

${ENV}`,
  { label: `build ${issue} (${model})`, schema: BUILD_SCHEMA, isolation: 'worktree', model },
)
let build = await buildOn(tier)
// A cheaper tier that could not finish gets one retry a tier up. An unclear
// issue is not retried: a stronger model would only guess more confidently.
if (tier !== 'opus' && (!build || build.outcome === 'unreproduced' || (build.outcome === 'built' && build.branches.length === 0))) {
  const from = tier
  tier = nextTier(tier)
  log(`${issue}: the ${from} build did not finish; retrying on ${tier}`)
  build = await buildOn(tier)
}
if (!build) throw new Error('Build returned nothing')
if (build.outcome !== 'built' || build.branches.length === 0) {
  await agent(
    `Post one comment on Linear issue ${issue} explaining why the unattended build stopped, in a few lines: ${build.outcome}. ${build.question ?? ''} Then move the card to Blocked. ${GITHUB}`,
    { label: `report ${issue}`, effort: 'low' },
  )
  log(`${issue} stopped: ${build.outcome}`)
  return { issue, stopped: build.outcome, detail: build.question }
}

// ---------------------------------------------------------------- Review
let unresolved = []
if (t.kind === 'feature') {
  phase('Review')
  const branchList = () => build.branches.map((b, i) => `${i + 1}. \`${b.branch}\` (base: \`${i === 0 ? 'main' : build.branches[i - 1].branch}\`): ${b.purpose}`).join('\n')
  for (let round = 0; ; round++) {
    const review = await agent(
      `${brief(REVIEWER)}Review the branches built for Linear issue ${issue} ("${t.title}"), in landing order:\n${branchList()}\n\nThe implementer's own report: ${build.summary}\nAssumptions it made: ${build.assumptions.join('; ') || 'none'}\n\n${GITHUB}\n\n${ENV}`,
      { label: `review ${issue} r${round + 1}`, schema: REVIEW_SCHEMA, isolation: 'worktree', effort: 'high', model: atLeast(tier, 'sonnet') },
    )
    unresolved = review?.blocking ?? []
    if (unresolved.length === 0 || round >= MAX_FIX_ROUNDS) break
    log(`${issue} review round ${round + 1}: ${unresolved.length} blocking finding(s)`)
    const fixed = await agent(
      `${brief(IMPLEMENTER)}You are fixing review findings on already-pushed branches for Linear issue ${issue} (kind: feature). Check out each branch from \`origin/<branch>\`, fix, re-run the checks, and push. When you change an earlier piece, merge its branch into each later piece (\`git merge <earlier branch>\`) so every later branch still contains it, and push. Never rebase or force-push. Branches:\n${branchList()}\n\nBlocking findings:\n${unresolved.map((f) => `- ${f}`).join('\n')}\n\nReturn the full report again, updated (keep the same branches unless a split was genuinely needed). ${GITHUB}\n\n${ENV}`,
      { label: `fix review ${issue} r${round + 1}`, schema: BUILD_SCHEMA, isolation: 'worktree', model: tier },
    )
    if (fixed?.outcome === 'built' && fixed.branches.length) build = fixed
  }
  if (unresolved.length) log(`${issue}: ${unresolved.length} finding(s) still open after ${MAX_FIX_ROUNDS} fix rounds; they go in the PR body.`)
}

// ---------------------------------------------------------------- Land
// Every PR targets main. A sequence lands one PR at a time: the next opens only
// once the one before it has merged, with main merged into its branch first, so
// its diff is its own and nothing is ever rebased or force-pushed. The code is
// finished by now, so every landing agent is mechanical and runs on Sonnet.
phase('Land')
const LANDING = { model: 'sonnet', effort: 'low' }
const n = build.branches.length
const action = t.kind === 'fix' ? 'Fix' : 'Implement'
const prs = []
const problems = []
const WAIT_MINUTES = 90

for (let i = 0; i < n; i++) {
  const b = build.branches[i]
  const prev = prs[i - 1]
  if (prev) {
    const waited = await agent(
      `Wait for PR #${prev.number} (${prev.url}) to merge. ${GITHUB}

Poll \`gh pr view ${prev.number} --repo trygroove/groove --json state,mergedAt,labels\` every two to five minutes (the Monitor tool if you have it, else a bounded shell loop) for up to ${WAIT_MINUTES} minutes. It merges on its own once CI is green, unless it is labelled \`needs-approval\` (then the product owner has to approve it, which may not happen in time). Return \`merged\`, \`closed\` (closed without merging), or \`waiting\` if it is still open when the time runs out, with its labels. Change nothing.`,
      { label: `wait #${prev.number}`, schema: WAIT_SCHEMA, ...LANDING },
    )
    if (waited?.state !== 'merged') {
      const remaining = build.branches.slice(i)
      const rest = remaining.map((x) => `\`${x.branch}\``).join(', ')
      const why = waited?.state === 'closed'
        ? `#${prev.number} was closed without merging`
        : `#${prev.number} has not merged yet${waited?.labels?.includes('needs-approval') ? ' (it needs approval)' : ''}`
      // The handoff note: the next run starts from this, not from the diffs.
      await agent(
        `Post one comment on Linear issue ${issue}, headed "**Handoff from /ship**". It says this run opened ${prs.map((p) => `${p.url}`).join(', ')} and stopped because ${why}, and that the remaining work is pushed and opens as its own PR${remaining.length > 1 ? 's' : ''} against main once #${prev.number} has landed: then move the card to Ready again and /ship continues from here. Do not move the card. Then the note the next run works from:

- Remaining pieces, in landing order, each with its branch, what it contains and the branch it was built on (merge main into it before opening it):
${remaining.map((x, j) => `  ${i + j + 1} of ${n}: \`${x.branch}\` (built on \`${build.branches[i + j - 1].branch}\`): ${x.purpose}`).join('\n')}
- What the whole issue builds: ${build.summary}
- Assumptions made without asking: ${build.assumptions.join('; ') || 'none'}
- Checks run on the branches: ${build.checks}
${build.uiChanged ? `- Screenshots already captured (for the PR whose branch changed the UI):\n${build.screenshots || '  MISSING'}\n` : ''}${unresolved.length ? `- Review findings still open (for the last PR's body):\n${unresolved.map((f) => `  - ${f}`).join('\n')}\n` : ''}
Copy the facts as given; do not summarise them away. ${GITHUB}`,
        { label: `report ${issue}`, ...LANDING },
      )
      problems.push(`${why}; ${rest} not opened`)
      log(`${issue}: ${why}; stopped before ${rest}`)
      break
    }
    await agent(
      `Bring \`${b.branch}\` up to date with main before its PR opens: it was built on \`${build.branches[i - 1].branch}\`, which has now merged as #${prev.number}. ${GITHUB}

Check out \`origin/${b.branch}\`, run \`git merge origin/main\` (expect it to be clean: the earlier piece is in both sides), resolve any conflict so both sides' behaviour survives, run \`bun run typecheck\` and \`bun run check\`, and push with a plain \`git push\`. Never rebase or force-push. If the merge cannot keep both sides' behaviour, stop and say so.

${ENV}`,
      { label: `update ${b.branch}`, isolation: 'worktree', ...LANDING },
    )
  }
  const landed = await agent(
    `Open the pull request for branch \`${b.branch}\` of Linear issue ${issue}: ${b.purpose}. ${GITHUB}

- Base: \`main\`. Open it **ready for review, not as a draft**.
- Title: \`${action} ${issue}: <what this PR does>\`${n > 1 ? ' (this piece\'s purpose)' : ` (e.g. "${action} ${issue}: ${t.title}")`}.
- Body: follow \`.github/pull_request_template.md\` (fill its sections from the facts below). ${n > 1 ? `Say "${i + 1} of ${n}${prev ? `, follows #${prev.number}` : ''}". ` : ''}${i === n - 1 ? `\`Completes ${issue}\`` : `\`Refs ${issue}\` (not Completes: this is not the last PR)`}. Never \`Closes\` or \`Fixes\`: the card goes to QA when this merges, and QA moves it to Done after testing it on production.

Facts for the body:
- Summary of the whole issue: ${build.summary}
${build.rootCause ? `- Root cause: ${build.rootCause}\n` : ''}${build.redEvidence ? `- Regression test, red before the fix:\n\`\`\`\n${build.redEvidence}\n\`\`\`\n` : ''}- Assumptions made without asking: ${build.assumptions.join('; ') || 'none'}
- Checks: ${build.checks}
- New Google Cloud APIs: ${build.cloudApis?.length ? build.cloudApis.join('; ') : 'none'}. For each one this branch needs, fill the template's Cloud APIs section: the API, why it is required (the code that needs it and what that code does), and \`gcloud services enable <api> --project <project-id>\`, because the deploy fails until the product owner runs it. If this branch needs none, delete that section.
- Built on: ${tier} (${t.tierReason}). Put this one line in the body so the routing can be judged.
- Screenshots (put them in the Screenshots section if this branch changed the UI, or if it is the last PR): ${build.uiChanged ? build.screenshots || 'MISSING: say so plainly in the body' : 'No UI change'}
${i === n - 1 && unresolved.length ? `- Review findings still open after ${MAX_FIX_ROUNDS} fix rounds (list them under a "Open review findings" heading):\n${unresolved.map((f) => `  - ${f}`).join('\n')}\n` : ''}
Add no labels: \`.github/workflows/merge.yml\` queues the PR on its own, or flags it \`needs-approval\` if it touches a gated path. After writing the body, re-read it and check no image link contains a backtick. Confirm the PR exists before returning its number and URL.`,
    { label: `land ${b.branch}`, schema: LAND_SCHEMA, ...LANDING },
  )
  if (!landed?.number) {
    problems.push(`no PR opened for ${b.branch}`)
    log(`${issue}: no PR opened for ${b.branch}`)
    break
  }
  prs.push({ number: landed.number, url: landed.url })
  problems.push(...(landed.problems ?? []))
  log(`${issue}: opened ${landed.url}`)
}

return { issue, kind: t.kind, tier, prs, openFindings: unresolved, problems }
